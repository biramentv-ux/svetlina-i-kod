export const lessonCount = (c: Course) => c.modules.reduce((n, m) => n + m.l.length, 0);
export const totalMinutes = (c: Course) => c.modules.reduce((n, m) => n + m.l.reduce((a, l) => a + l[1], 0), 0);
export const fmtHours = (min: number) => {
  const h = Math.floor(min / 60);
  const m = min % 60;
  return h ? `${h} ч ${m ? m + " мин" : ""}`.trim() : `${m} мин`;
};
